#!/usr/bin/env python3
"""Check the Cakezz repo and keep STATE.md up to date.

  python scripts/check_repo.py                 report
  python scripts/check_repo.py --need N        exit 1 unless the parts Part N needs are DONE
  python scripts/check_repo.py --write-state   also rewrite STATE.md
"""
import json, re, sys
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
CFG = json.loads((ROOT / "scripts" / "ownership.json").read_text())
PARTS = sorted(CFG["names"], key=int)


def status(n):
    f = ROOT / "state" / f"part-{n}.md"
    if not f.exists():
        return "NOT_STARTED"
    m = re.search(r"^Status:\s*([A-Z_]+)", f.read_text(errors="replace"), re.M)
    return m.group(1) if m else "NOT_STARTED"


def problems():
    out = []
    for p in sorted(ROOT.iterdir()):
        if p.name in CFG["allowed_top_level"] or p.name in (".git", "__pycache__", ".pytest_cache"):
            continue
        out.append(f"STRAY top-level item '{p.name}'. Move it into shop/ or rulelock/ or delete it. "
                   "There must be ONE app, not a second one.")
    if (ROOT / "cakezz").exists():
        out.append("Nested 'cakezz/cakezz/' folder. Flatten it.")
    for n in PARTS:
        if status(n) == "DONE":
            for f in CFG["expects"].get(n, []):
                if not (ROOT / f).exists():
                    out.append(f"Part {n} is DONE but '{f}' is missing.")
    return out


def runnable():
    return [n for n in PARTS if status(n) != "DONE" and all(status(str(d)) == "DONE" for d in CFG["needs"][n])]


def state_md():
    rows = ["| Part | What | Status | Needs |", "|---|---|---|---|"]
    for n in PARTS:
        needs = ", ".join(str(d) for d in CFG["needs"][n]) or "-"
        rows.append(f"| {n} | {CFG['names'][n]} | {status(n)} | {needs} |")
    nxt = runnable()
    return ("# STATE (generated by scripts/check_repo.py; do not edit by hand)\n\n" + "\n".join(rows) +
            f"\n\nCan be run now: {', '.join('Part ' + n for n in nxt) or 'nothing (all done)'}\n"
            "Details for each part: state/part-N.md\n")


def main():
    a = sys.argv[1:]
    if "--need" in a:
        n = a[a.index("--need") + 1]
        missing = [d for d in CFG["needs"][n] if status(str(d)) != "DONE"]
        if missing:
            print(f"STOP: Part {n} needs Part(s) {missing} to be DONE first. "
                  "Attach the newest repo zip that includes them.")
            sys.exit(1)
        print(f"OK: prerequisites for Part {n} are DONE.")
    probs = problems()
    print("Parts:", "  ".join(f"{n}={status(n)}" for n in PARTS))
    print("Can be run now:", ", ".join(runnable()) or "nothing")
    for p in probs:
        print("PROBLEM:", p)
    if "--write-state" in a:
        (ROOT / "STATE.md").write_text(state_md())
        print("STATE.md updated.")
    sys.exit(1 if probs else 0)


main()
