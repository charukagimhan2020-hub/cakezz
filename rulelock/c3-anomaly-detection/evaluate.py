"""Precision / recall of the model at the hold and reject thresholds. Run: python evaluate.py

HONEST WARNING: the training data, the 'abuse' data and the labels are all generated by us from the same
assumptions, so these numbers are circular. They show that the pipeline works, not how it would do on real traffic.
"""
import numpy as np

import scoring
import synthetic_data as sd
from features import FEATURE_NAMES, session_to_features
from train_model import build_model

FIXTURES = [  # (name, features, truth) hand-written examples
    ("typical_customer", [1, 18, 1, 1], "normal"),
    ("slow_customer", [0, 420, 1, 1], "normal"),
    ("shared_device_two_accounts", [1, 70, 2, 1], "normal"),
    ("coupon_burst", [9, 2, 1, 1], "abuse"),
    ("account_farming", [5, 8, 7, 4], "abuse"),
    ("address_farming", [1, 40, 1, 6], "abuse"),
]


def _clip(rows):
    return np.vstack([session_to_features(dict(zip(FEATURE_NAMES, r)))[0] for r in rows])


def _decision(score, hold, reject):
    return "reject" if score < reject else "hold" if score < hold else "accept"


def run(model=None):
    """Returns a dict with per-group rows, precision/recall, fixtures. Does not touch model.joblib."""
    model = model or build_model()
    t = scoring.thresholds()
    hold, reject = t["hold"], t["reject"]
    groups = [
        ("normal: demo definition", "normal", sd.generate_demo_normal(1000, seed=11)),
        ("normal: broad training mix", "normal", sd.generate_normal_sessions(1000, seed=99)),
        ("abuse: coupon stacking", "abuse", sd.generate_coupon_stacking(200, seed=7)),
        ("abuse: multi account", "abuse", sd.generate_multi_account(200, seed=8)),
        ("abuse: COD address farming", "abuse", sd.generate_cod_address_farming(200, seed=9)),
    ]
    rows, scores_by_label = [], {"normal": [], "abuse": []}
    for name, label, data in groups:
        s = model.decision_function(_clip(data)).reshape(-1)
        rows.append({"group": name, "label": label, "n": len(s), "mean": float(s.mean()), "min": float(s.min()),
                     "max": float(s.max()), "hold_pct": float((s < hold).mean() * 100),
                     "reject_pct": float((s < reject).mean() * 100)})
        if name != "normal: demo definition":          # the demo-definition group is a subset-style check, not mixed in
            scores_by_label[label].append(s)
    normal, abuse = np.concatenate(scores_by_label["normal"]), np.concatenate(scores_by_label["abuse"])
    pr = {}
    for label, cutoff in (("hold", hold), ("reject", reject)):
        tp, fn = int((abuse < cutoff).sum()), int((abuse >= cutoff).sum())
        fp = int((normal < cutoff).sum())
        pr[label] = {"cutoff": cutoff, "precision": tp / (tp + fp) if tp + fp else 1.0,
                     "recall": tp / (tp + fn) if tp + fn else 0.0, "tp": tp, "fp": fp, "fn": fn}
    fixtures = []
    for name, feats, truth in FIXTURES:
        score = float(model.decision_function(_clip([feats]))[0])
        fixtures.append({"name": name, "truth": truth, "score": score, "decision": _decision(score, hold, reject)})
    return {"rows": rows, "pr": pr, "fixtures": fixtures, "hold": hold, "reject": reject,
            "n_normal": len(normal), "n_abuse": len(abuse)}


def main():
    r = run()
    print(f"Thresholds: hold < {r['hold']}, reject < {r['reject']}   (lower score = more anomalous)")
    print(f"\n{'group':30s} {'n':>5s} {'mean':>7s} {'min':>7s} {'max':>7s} {'%hold+':>7s} {'%reject':>8s}")
    for x in r["rows"]:
        print(f"{x['group']:30s} {x['n']:5d} {x['mean']:7.3f} {x['min']:7.3f} {x['max']:7.3f} {x['hold_pct']:6.0f}% {x['reject_pct']:7.0f}%")
    print(f"\nPrecision / recall (abuse = positive; {r['n_normal']} broad normal vs {r['n_abuse']} abuse sessions)")
    print(f"{'cutoff':8s} {'value':>7s} {'precision':>10s} {'recall':>8s} {'TP':>5s} {'FP':>5s} {'FN':>5s}")
    for label in ("hold", "reject"):
        p = r["pr"][label]
        print(f"{label:8s} {p['cutoff']:7.2f} {p['precision']:10.3f} {p['recall']:8.3f} {p['tp']:5d} {p['fp']:5d} {p['fn']:5d}")
    print("\nHand-written fixtures")
    for f in r["fixtures"]:
        print(f"  {f['name']:28s} truth={f['truth']:6s} score={f['score']:7.3f} -> {f['decision']}")
    print("\nCircular evaluation: synthetic training data, synthetic abuse, labels made by us. Not a real-world benchmark.")


if __name__ == "__main__":
    main()
